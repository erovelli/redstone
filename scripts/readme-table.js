// The README's component table, generated from the catalogue and the element files so that it cannot drift.
//
//   node scripts/readme-table.js           rewrite the table in README.md (between the components markers)
//   node scripts/readme-table.js --check   exit 1 if README.md is out of date (the readme suite runs this check)
(function () {
'use strict';
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const C = require(path.join(ROOT, 'src', 'index.js'));
const START = '<!-- components:start (generated by scripts/readme-table.js; do not edit) -->';
const END = '<!-- components:end -->';

// Every element: its tag, the entry (or entries) it builds and the one-line description from its file's header.
function elements() {
  const dir = path.join(ROOT, 'src', 'ui', 'components');
  const out = [];
  for (const f of fs.readdirSync(dir).filter(n => n.endsWith('.js')).sort()) {
    const src = fs.readFileSync(path.join(dir, f), 'utf8');
    const head = (src.match(/^\/\/ <rs-[^>]+>(?: and <rs-[^>]+>)?: ([^\n]*)/m) || [])[1] || '';
    const line = head.split(/(?<=\.)\s/)[0].replace(/\.$/, '');
    const tags = [...src.matchAll(/define\('(rs-[a-z]+)'/g)].map(m => m[1]);
    const ids = [...new Set([...src.matchAll(/'(ui-[a-z-]+)'/g)].map(m => m[1]))].filter(id => C.get(id))
      .sort((a, b) => C.entries.indexOf(C.get(a)) - C.entries.indexOf(C.get(b)));
    out.push({ file: `src/ui/components/${f}`, tags, ids, line });
  }
  return out;
}

const cell = s => String(s).replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim().replace(/(<\/?[a-z][^>]*>)/g, '`$1`');
const cap = s => s.charAt(0).toUpperCase() + s.slice(1);
const firstSentence = s => cell(s).split(/(?<=\.)\s/)[0];

function table() {
  const rows = ['| Element | What it is | Strict | Deviations |', '|---|---|---|---|'];
  for (const e of elements()) {
    const entries = e.ids.map(id => C.get(id));
    const strict = entries.map(x => (x.strict ? 'yes' : 'no')).join(' / ');
    const devs = entries.flatMap(x => (x.deviations || []).map(d => `${entries.length > 1 ? `\`${x.id}\`: ` : ''}${firstSentence(d)}`));
    const named = entries.length > 1 ? ` (${e.ids.map(id => `\`${id}\``).join(' / ')})` : '';
    rows.push(`| ${e.tags.map(t => `\`<${t}>\``).join(', ')} | ${cap(cell(e.line))} | ${strict}${named} | ${devs.join(' ') || 'none'} |`);
  }
  const all = C.entries.filter(x => x.id.startsWith('ui-'));
  rows.push('', `${all.filter(x => x.strict).length} of ${all.length} UI entries are strict; every deviation is listed in the entry and on the docs page.`);
  return rows.join('\n');
}

function render(readme) {
  const i = readme.indexOf(START), j = readme.indexOf(END);
  if (i < 0 || j < i) throw new Error('README.md has no components markers');
  return readme.slice(0, i + START.length) + '\n' + table() + '\n' + readme.slice(j);
}

module.exports = { table, render, elements };

if (require.main === module) {
  const file = path.join(ROOT, 'README.md');
  const now = fs.readFileSync(file, 'utf8');
  const next = render(now);
  if (process.argv.includes('--check')) {
    if (now !== next) {
      console.error('README.md component table is out of date: run node scripts/readme-table.js');
      process.exit(1);
    }
    console.log('README.md component table is up to date.');
  } else {
    fs.writeFileSync(file, next);
    console.log('README.md component table written.');
  }
}
})();
